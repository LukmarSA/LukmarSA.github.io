-- =====================================================================
-- 002 — Mapa: ubicaciones, radioenlaces e historial de ubicación de activos
-- =====================================================================
--
-- Qué agrega
--   tipos_ubicacion      Catálogo configurable (torre, oficina, bodega, …).
--                        Mismo patrón que estado_opciones: clave "valor"
--                        inmutable, "activo" para retirar sin borrar.
--   ubicaciones          Cualquier lugar con coordenadas. Una torre es una
--                        ubicación de tipo 'torre' (así una azotea con radio
--                        no tiene que existir dos veces).
--   equipos_radioenlace  Radios instalados en una ubicación. "activo_id" es
--                        opcional (un radio del proveedor no es un activo
--                        nuestro) y único: un activo no puede ser dos equipos.
--   enlaces              Pares de equipos con línea de vista. Un enlace es
--                        simétrico: A↔B se guarda una sola vez (índice único
--                        sobre LEAST/GREATEST) y un equipo puede tener varios
--                        enlaces (sirve para PtP y PtMP).
--   historial_ubicacion  Tramos desde/hasta por activo, como historial_custodia.
--                        Mover un activo = un solo INSERT: el trigger cierra el
--                        tramo vigente con la fecha del nuevo.
--
-- Decisiones que conviene no "arreglar" sin leer esto
--   * Las FK hacia activos(id) son ON DELETE CASCADE / SET NULL, nunca
--     RESTRICT: f_dar_baja() BORRA la fila de activos (el snapshot va a
--     bajas.activo), así que un RESTRICT rompería "Dar de baja".
--   * f_dar_baja/f_restaurar_baja se reemplazan con la MISMA firma (sin
--     sobrecargas nuevas en pg_proc) solo para guardar y restaurar el
--     historial de ubicación en el snapshot, igual que ya hacen con el de
--     custodia. Al restaurar, el activo recibe un id nuevo (comportamiento
--     previo de f_restaurar_baja) y sus tramos se reinsertan con ese id;
--     los de una ubicación que ya no exista se omiten para no bloquear la
--     restauración.
--   * Un activo vinculado a un equipo de radioenlace se ubica a través del
--     equipo: el trigger de equipos lo mueve solo, y los triggers de
--     historial_ubicacion impiden moverlo o sacarlo "por fuera".
--   * Escritura: ubicaciones/equipos/enlaces/tipos solo administrador
--     (es_admin(), como tipos_activo). historial_ubicacion usa la acción
--     nueva 'asignar_ubicacion' de la matriz (puede()), más
--     'restaurar_baja' para que f_restaurar_baja pueda reinsertar tramos,
--     igual que ins_historial en historial_custodia.
--   * Lectura: a diferencia de tipos_activo (SELECT abierto), ubicaciones,
--     equipos e historial exigen puede('ver_listado') o puede('ver_mapa'),
--     y enlaces puede('ver_mapa'): son la topología de la red y no deben
--     quedar legibles con la clave publicable (rol anon).
--   * GRANT explícito a anon/authenticated: el ACL por defecto de postgres
--     en public solo da Dxtm a esos roles, por eso una tabla creada desde el
--     SQL Editor responde "permission denied" sin él. Las columnas id son
--     IDENTITY, que no necesita GRANT sobre la secuencia.
--   * Fechas "de hoy" en el servidor: (now() AT TIME ZONE 'America/Guayaquil')::date,
--     no current_date (la base corre en UTC y después de las 19:00 en
--     Ecuador current_date ya es mañana).
--
-- Cómo correrla: pegar TODO el archivo en el SQL Editor de Supabase y
-- ejecutar. Va en una sola transacción: si algo falla, no queda nada a medias.
-- =====================================================================

