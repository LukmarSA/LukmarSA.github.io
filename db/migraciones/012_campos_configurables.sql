-- ---------------------------------------------------------------------
-- 6. Baja / restauración: la copia lleva también personalizados.
--    MISMA firma que las de la 002 (CREATE OR REPLACE conserva dueño y
--    permisos, y no crea sobrecargas). Los cambios están marcados «012».
-- ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.f_dar_baja(p_activo_id integer, p_motivo text)
 RETURNS void
 LANGUAGE plpgsql
AS $function$ declare v_snapshot jsonb; begin select jsonb_build_object( 'id', a.id, 'propiedad', a.propiedad, 'tipo', a.tipo, 'marca', a.marca, 'modelo', a.modelo, 'serie', a.serie, 'nombre_dispositivo', a.nombre_dispositivo, 'mac_wifi', a.mac_wifi, 'mac_ethernet', a.mac_ethernet, 'sistema_operativo', a.sistema_operativo, 'ram_gb', a.ram_gb, 'disco_gb', a.disco_gb, 'procesador', a.procesador, 'proveedor', a.proveedor, 'fecha_adquisicion', a.fecha_adquisicion, 'celular_gmail', a.celular_gmail, 'celular_password', a.celular_password, 'trazabilidad', a.trazabilidad, 'estado', a.estado, 'valor_compra', a.valor_compra, 'vida_util_anios', a.vida_util_anios, 'color', a.color, 'longitud_m', a.longitud_m, 'fotos', a.fotos, 'historial_custodia', coalesce(( select jsonb_agg(jsonb_build_object('orden', h.orden, 'tipo_custodio', h.tipo_custodio, 'nombre', h.nombre, 'cargo', h.cargo, 'desde', h.desde, 'hasta', h.hasta, 'tipo_devolucion', h.tipo_devolucion, 'tipo_entrega', h.tipo_entrega, 'observacion_entrega', h.observacion_entrega, 'observacion_devolucion', h.observacion_devolucion) order by h.orden) from public.historial_custodia h where h.activo_id = a.id), '[]'::jsonb)
  -- «002» historial de ubicación en el snapshot (con el nombre, por si la ubicación se borra después)
  , 'historial_ubicacion', coalesce(( select jsonb_agg(jsonb_build_object('ubicacion_id', hu.ubicacion_id, 'ubicacion', u.nombre, 'desde', hu.desde, 'hasta', hu.hasta, 'notas', hu.notas, 'registrado_por', hu.registrado_por) order by hu.desde, hu.id) from public.historial_ubicacion hu left join public.ubicaciones u on u.id = hu.ubicacion_id where hu.activo_id = a.id), '[]'::jsonb)
  -- «012» valores de los campos nuevos
  , 'personalizados', coalesce(a.personalizados, '{}'::jsonb)
  ) into v_snapshot from public.activos a where a.id = p_activo_id; if v_snapshot is null then raise exception 'Activo % no encontrado', p_activo_id; end if; insert into public.bajas (activo, motivo, dado_de_baja_por) values (v_snapshot, p_motivo, auth.uid()); delete from public.activos where id = p_activo_id; end; $function$;

CREATE OR REPLACE FUNCTION public.f_restaurar_baja(p_baja_id bigint)
 RETURNS integer
 LANGUAGE plpgsql
AS $function$ declare v_activo jsonb; v_nuevo_id integer; begin select activo into v_activo from public.bajas where id = p_baja_id; if v_activo is null then raise exception 'Baja % no encontrada', p_baja_id; end if;
  -- «012» los valores de los campos nuevos vuelven tal cual (no se revalidan)
  perform set_config('lukmar.restaurando_baja', 'si', true);
  insert into public.activos (propiedad, tipo, marca, modelo, serie, nombre_dispositivo, mac_wifi, mac_ethernet, sistema_operativo, ram_gb, disco_gb, procesador, proveedor, fecha_adquisicion, celular_gmail, celular_password, trazabilidad, estado, valor_compra, vida_util_anios, color, longitud_m, fotos, personalizados) values (case when v_activo->>'propiedad' = 'propio' then coalesce(v_activo->>'empresa', 'lukmar') else v_activo->>'propiedad' end, v_activo->>'tipo', v_activo->>'marca', v_activo->>'modelo', v_activo->>'serie', v_activo->>'nombre_dispositivo', v_activo->>'mac_wifi', v_activo->>'mac_ethernet', v_activo->>'sistema_operativo', (v_activo->>'ram_gb')::numeric, (v_activo->>'disco_gb')::numeric, v_activo->>'procesador', v_activo->>'proveedor', (v_activo->>'fecha_adquisicion')::date, v_activo->>'celular_gmail', v_activo->>'celular_password', coalesce(v_activo->'trazabilidad', 'null'::jsonb), coalesce(v_activo->>'estado', 'uso'), (v_activo->>'valor_compra')::numeric, (v_activo->>'vida_util_anios')::numeric, v_activo->>'color', (v_activo->>'longitud_m')::numeric, case when jsonb_typeof(v_activo->'fotos') = 'array' then (select array_agg(x) from jsonb_array_elements_text(v_activo->'fotos') x) else array[]::text[] end, case when jsonb_typeof(v_activo->'personalizados') = 'object' then v_activo->'personalizados' else '{}'::jsonb end ) returning id into v_nuevo_id;
  perform set_config('lukmar.restaurando_baja', '', true);
  insert into public.historial_custodia (activo_id, orden, tipo_custodio, nombre, cargo, desde, hasta, tipo_devolucion, tipo_entrega, observacion_entrega, observacion_devolucion) select v_nuevo_id, (t->>'orden')::int, t->>'tipo_custodio', t->>'nombre', t->>'cargo', (t->>'desde')::date, (t->>'hasta')::date, t->>'tipo_devolucion', t->>'tipo_entrega', t->>'observacion_entrega', coalesce(t->>'observacion_devolucion', t->>'observacion') from jsonb_array_elements(coalesce(v_activo->'historial_custodia', '[]'::jsonb)) as t;
  -- «002» reinsertar el historial de ubicación con el id nuevo (se omiten tramos de ubicaciones que ya no existen)
  insert into public.historial_ubicacion (activo_id, ubicacion_id, desde, hasta, notas, registrado_por) select v_nuevo_id, (t->>'ubicacion_id')::bigint, (t->>'desde')::date, (t->>'hasta')::date, t->>'notas', (t->>'registrado_por')::uuid from jsonb_array_elements(coalesce(v_activo->'historial_ubicacion', '[]'::jsonb)) as t where exists (select 1 from public.ubicaciones u where u.id = (t->>'ubicacion_id')::bigint);
  delete from public.bajas where id = p_baja_id; return v_nuevo_id; end; $function$;

COMMIT;
