-- 2a. Un enlace une equipos de ubicaciones distintas.
CREATE FUNCTION public.f_enlaces_validar()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_u_origen  bigint;
  v_u_destino bigint;
BEGIN
  SELECT ubicacion_id INTO v_u_origen  FROM public.equipos_radioenlace WHERE id = NEW.equipo_origen_id;
  SELECT ubicacion_id INTO v_u_destino FROM public.equipos_radioenlace WHERE id = NEW.equipo_destino_id;
  IF v_u_origen = v_u_destino THEN
    RAISE EXCEPTION 'Un enlace debe unir equipos de ubicaciones distintas.' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_enlaces_validar
  BEFORE INSERT OR UPDATE OF equipo_origen_id, equipo_destino_id ON public.enlaces
  FOR EACH ROW EXECUTE FUNCTION public.f_enlaces_validar();

-- 2b. Un equipo no puede mudarse a la ubicación del otro extremo de uno de sus enlaces.
CREATE FUNCTION public.f_equipos_radioenlace_validar()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NEW.ubicacion_id IS DISTINCT FROM OLD.ubicacion_id AND EXISTS (
    SELECT 1
      FROM public.enlaces l
      JOIN public.equipos_radioenlace o
        ON o.id = CASE WHEN l.equipo_origen_id = NEW.id THEN l.equipo_destino_id ELSE l.equipo_origen_id END
     WHERE (l.equipo_origen_id = NEW.id OR l.equipo_destino_id = NEW.id)
       AND o.ubicacion_id = NEW.ubicacion_id
  ) THEN
    RAISE EXCEPTION 'El equipo quedaría en la misma ubicación que el otro extremo de uno de sus enlaces.' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_equipos_radioenlace_validar
  BEFORE UPDATE OF ubicacion_id ON public.equipos_radioenlace
  FOR EACH ROW EXECUTE FUNCTION public.f_equipos_radioenlace_validar();

-- 2c. El activo vinculado a un equipo queda ubicado donde está el equipo
--     (abre un tramo nuevo; el trigger 2d cierra el anterior).
CREATE FUNCTION public.f_equipos_radioenlace_sincronizar_activo()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NEW.activo_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.historial_ubicacion
     WHERE activo_id = NEW.activo_id AND hasta IS NULL AND ubicacion_id = NEW.ubicacion_id
  ) THEN
    INSERT INTO public.historial_ubicacion (activo_id, ubicacion_id, desde, notas)
    VALUES (NEW.activo_id, NEW.ubicacion_id, (now() AT TIME ZONE 'America/Guayaquil')::date,
            'Automático: instalado como equipo de radioenlace «' || NEW.nombre || '»');
  END IF;
  RETURN NULL;
END $$;

CREATE TRIGGER trg_equipos_radioenlace_sincronizar_activo
  AFTER INSERT OR UPDATE OF activo_id, ubicacion_id ON public.equipos_radioenlace
  FOR EACH ROW EXECUTE FUNCTION public.f_equipos_radioenlace_sincronizar_activo();

-- 2d. Abrir un tramo vigente cierra el anterior (con la fecha del nuevo).
CREATE FUNCTION public.f_historial_ubicacion_antes_insertar()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_vigente record;
  v_equipo  record;
BEGIN
  -- Un tramo ya cerrado (carga histórica, o f_restaurar_baja) no toca el vigente.
  IF NEW.hasta IS NOT NULL THEN
    RETURN NEW;
  END IF;

  SELECT e.nombre AS equipo, u.nombre AS ubicacion INTO v_equipo
    FROM public.equipos_radioenlace e
    JOIN public.ubicaciones u ON u.id = e.ubicacion_id
   WHERE e.activo_id = NEW.activo_id AND e.ubicacion_id <> NEW.ubicacion_id;
  IF FOUND THEN
    RAISE EXCEPTION 'Este activo está instalado como equipo de radioenlace «%» en «%»: muévelo editando ese equipo.',
      v_equipo.equipo, v_equipo.ubicacion USING ERRCODE = '23514';
  END IF;

  SELECT id, ubicacion_id, desde INTO v_vigente
    FROM public.historial_ubicacion
   WHERE activo_id = NEW.activo_id AND hasta IS NULL
   FOR UPDATE;
  IF FOUND THEN
    IF v_vigente.ubicacion_id = NEW.ubicacion_id THEN
      RAISE EXCEPTION 'El activo ya está en esa ubicación.' USING ERRCODE = '23514';
    END IF;
    IF NEW.desde < v_vigente.desde THEN
      RAISE EXCEPTION 'La fecha del movimiento (%) es anterior a la llegada del activo a su ubicación actual (%).',
        to_char(NEW.desde, 'DD/MM/YYYY'), to_char(v_vigente.desde, 'DD/MM/YYYY') USING ERRCODE = '23514';
    END IF;
    UPDATE public.historial_ubicacion SET hasta = NEW.desde WHERE id = v_vigente.id;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_historial_ubicacion_antes_insertar
  BEFORE INSERT ON public.historial_ubicacion
  FOR EACH ROW EXECUTE FUNCTION public.f_historial_ubicacion_antes_insertar();

-- 2e. Reglas de edición de un tramo.
CREATE FUNCTION public.f_historial_ubicacion_antes_actualizar()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_equipo text;
BEGIN
  IF NEW.activo_id <> OLD.activo_id THEN
    RAISE EXCEPTION 'No se puede cambiar el activo de un tramo de ubicación.' USING ERRCODE = '23514';
  END IF;
  -- Corregir dónde o desde cuándo: solo administrador. auth.uid() NULL = sesión
  -- directa a la base (SQL Editor / service role), que no pasa por la RLS de la API.
  IF (NEW.ubicacion_id <> OLD.ubicacion_id OR NEW.desde <> OLD.desde)
     AND auth.uid() IS NOT NULL AND NOT coalesce(public.es_admin(), false) THEN
    RAISE EXCEPTION 'Solo un administrador puede corregir la ubicación o la fecha de inicio de un tramo.' USING ERRCODE = '42501';
  END IF;
  -- Sacar de su ubicación un activo que es equipo de radioenlace ahí: se hace desde el equipo.
  IF OLD.hasta IS NULL AND NEW.hasta IS NOT NULL THEN
    SELECT e.nombre INTO v_equipo
      FROM public.equipos_radioenlace e
     WHERE e.activo_id = OLD.activo_id AND e.ubicacion_id = OLD.ubicacion_id;
    IF FOUND THEN
      RAISE EXCEPTION 'Este activo está instalado como equipo de radioenlace «%»: desvincúlalo o mueve el equipo antes de sacarlo de esta ubicación.',
        v_equipo USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_historial_ubicacion_antes_actualizar
  BEFORE UPDATE ON public.historial_ubicacion
  FOR EACH ROW EXECUTE FUNCTION public.f_historial_ubicacion_antes_actualizar();

