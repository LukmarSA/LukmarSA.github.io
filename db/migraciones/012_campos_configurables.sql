      AND icono_svg !~* '<\s*script' AND icono_svg !~* 'javascript\s*:' AND icono_svg !~* '[\s/"'']on[a-z]+\s*=' AND icono_svg !~* '<\s*foreignObject'));
COMMENT ON COLUMN public.tipos_ubicacion.icono_svg IS 'Ícono de la burbuja en el mapa (SVG con viewBox). NULL = el dibujo de fábrica (migración 012).';

-- ---------------------------------------------------------------------
-- 4. Cambiar el nombre de un tipo de activo
-- ---------------------------------------------------------------------

CREATE FUNCTION public.renombrar_tipo_activo(p_viejo text, p_nuevo text)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_nuevo text := btrim(p_nuevo);
  v_n integer;
BEGIN
  IF NOT public.es_admin() THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Solo el administrador puede cambiar el nombre de un tipo.';
  END IF;
  IF p_viejo IS NULL OR NOT EXISTS (SELECT 1 FROM public.tipos_activo t WHERE t.nombre = p_viejo) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = format('El tipo «%s» no existe.', p_viejo);
  END IF;
  IF p_viejo = 'Celular' THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = '«Celular» no se puede renombrar: ese nombre activa los datos de celular.';
  END IF;
  IF v_nuevo IS NULL OR v_nuevo = '' OR char_length(v_nuevo) > 60 THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'El nombre nuevo no puede quedar vacío (hasta 60 caracteres).';
  END IF;
  IF v_nuevo = p_viejo THEN
    RETURN 0;
  END IF;
  IF EXISTS (SELECT 1 FROM public.tipos_activo t WHERE lower(btrim(t.nombre)) = lower(v_nuevo) AND t.nombre <> p_viejo) THEN
    RAISE EXCEPTION USING ERRCODE = '23505', MESSAGE = format('Ya existe un tipo que se llama «%s».', v_nuevo);
  END IF;
  SELECT count(*) INTO v_n FROM public.activos a WHERE a.tipo = p_viejo;
  -- activos_tipo_fkey (ON UPDATE CASCADE) lleva el nombre nuevo a activos.tipo.
  UPDATE public.tipos_activo SET nombre = v_nuevo WHERE nombre = p_viejo;
  UPDATE public.bajas SET activo = jsonb_set(activo, '{tipo}', to_jsonb(v_nuevo)) WHERE activo ->> 'tipo' = p_viejo;
  RETURN v_n;
END $$;
COMMENT ON FUNCTION public.renombrar_tipo_activo(text, text) IS 'Cambia el nombre de un tipo de activo: la FK lo lleva a los activos y la función a las copias de las bajas. Devuelve cuántos activos cambiaron (migración 012).';
REVOKE ALL ON FUNCTION public.renombrar_tipo_activo(text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.renombrar_tipo_activo(text, text) TO authenticated;

