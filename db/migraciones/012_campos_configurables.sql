-- 012 — Campos configurables de los activos (v10)
-- =====================================================================
--
-- Qué cambia
--   * campos_activo: las definiciones de los campos de los activos. Trae de
--     semilla los 9 de siempre («fijos»: son columnas de activos — serie,
--     sistema operativo, RAM, almacenamiento, procesador, las dos MAC, color
--     y longitud); el administrador agrega los suyos (IMEI, número de
--     línea…), con su tipo de dato: texto, texto largo, número (con unidad),
--     fecha, sí/no o lista de opciones. Un solo orden para todos los tipos.
--     A los fijos se les cambia la etiqueta, la unidad, el orden y las
--     reglas; no se borran, no se desactivan ni cambian de tipo de dato.
--   * activos.personalizados (jsonb): { <clave>: valor } de los campos
--     nuevos. Al guardar, la base mezcla lo que llega con lo que había
--     (OLD || NEW) y quita los null: así un campo que el tipo oculta no se
--     pierde y un campo vaciado se borra. Cada valor que cambia se valida
--     según su tipo de dato.
--   * tipos_activo.campos_obligatorios (jsonb): las claves obligatorias de
--     cada tipo (la app las exige en el formulario del activo).
--     campos_pertinentes sigue siendo la lista de claves que usa el tipo.
--   * «Único»: un campo marcado no puede repetir su valor entre activos
--     (sin distinguir mayúsculas ni espacios; los números, como números).
--     No se deja marcar si ya hay valores repetidos.
--   * «En el acta»: el campo sale en la descripción del ítem del acta.
--   * f_dar_baja / f_restaurar_baja: la copia lleva también personalizados.
--     MISMA firma (CREATE OR REPLACE conserva dueño y permisos); antes se
--     comprueba que sean las de la 002, para no pisar otra versión.
--   * renombrar_tipo_activo(viejo, nuevo): cambia el nombre de un tipo de
--     activo (la FK activos_tipo_fkey, con ON UPDATE CASCADE, lo lleva a los
--     activos) y también en las copias de las bajas, para que restaurarlas
--     no falle. Solo administradores; «Celular» no se renombra.
--   * tipos_ubicacion.icono_svg: el ícono de la burbuja en el mapa.
--
-- Sin esta migración la app (v10) funciona como el v9: se esconde lo que
-- falta. Y el v9 publicado sigue funcionando con ella aplicada.
--
-- Necesita la 011. Cómo correrla: pegar TODO el archivo en el SQL Editor de
-- Supabase y ejecutar. Va en una sola transacción: si algo falla, no queda
-- nada a medias. Si ya fue aplicada, se niega sin tocar nada.
-- =====================================================================

