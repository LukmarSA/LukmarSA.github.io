-- Valor normalizado para comparar «único»: sin mayúsculas ni espacios de
-- más; los números, como números (12, 12.0 y 12,00 son lo mismo).
CREATE FUNCTION public.f_valor_comparable(p_valor text, p_tipo text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = ''
AS $$
  SELECT CASE
    WHEN p_valor IS NULL OR btrim(p_valor) = '' THEN NULL
    WHEN p_tipo = 'numero' AND btrim(p_valor) ~ '^[-+]?([0-9]+[.]?[0-9]*|[.][0-9]+)([eE][-+]?[0-9]+)?$'
      THEN 'n:' || pg_catalog.trim_scale(btrim(p_valor)::numeric)::text
    ELSE 't:' || lower(regexp_replace(btrim(p_valor), '\s+', ' ', 'g'))
  END
$$;
COMMENT ON FUNCTION public.f_valor_comparable(text, text) IS 'Valor normalizado de un campo para la regla «único» (migración 012).';

-- Reglas de las definiciones: los fijos no se borran, no cambian de clave,
-- de tipo de dato ni se desactivan; las claves reservadas no se usan; las
-- listas traen opciones válidas; «único» no se marca con repetidos; y un
-- campo con valores no se borra ni cambia de tipo de dato.
CREATE FUNCTION public.f_campos_activo_validar()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_fijos constant jsonb := '{"serie":"serie","so":"sistema_operativo","ram_gb":"ram_gb","disco_gb":"disco_gb","procesador":"procesador","mac_wifi":"mac_wifi","mac_ethernet":"mac_ethernet","color":"color","longitud_m":"longitud_m"}';
  v_reservadas constant text[] := ARRAY['id','propiedad','tipo','marca','modelo','nombre_dispositivo','sistema_operativo','proveedor','fecha_adquisicion',
    'celular','celular_gmail','celular_password','gmail','password','trazabilidad','creado_en','valor_compra','vida_util_anios','fotos','estado',
    'personalizados','custodio','historial_custodia','historial_ubicacion','nombre','cargo','tag','acciones','ubicacion'];
  v_valores text[] := '{}';
  v_o jsonb;
  v_n integer;
  v_con_valores boolean;
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.fijo THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('«%s» es un campo de siempre: no se borra.', OLD.etiqueta);
    END IF;
    IF EXISTS (SELECT 1 FROM public.activos a WHERE a.personalizados ? OLD.clave)
       OR EXISTS (SELECT 1 FROM public.bajas b WHERE b.activo -> 'personalizados' ? OLD.clave) THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('El campo «%s» tiene valores guardados: desactívalo en vez de borrarlo.', OLD.etiqueta);
    END IF;
    RETURN OLD;
  END IF;

  NEW.etiqueta := btrim(NEW.etiqueta);
  NEW.unidad := nullif(btrim(NEW.unidad), '');

  IF TG_OP = 'INSERT' THEN
    IF NEW.fijo THEN
      IF (v_fijos ->> NEW.clave) IS DISTINCT FROM NEW.columna THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Solo los 9 campos de siempre son fijos.';
      END IF;
    ELSIF NEW.clave = ANY (v_reservadas) OR v_fijos ? NEW.clave THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('La clave «%s» está reservada: elige otra etiqueta.', NEW.clave);
    END IF;
  ELSE
    IF NEW.clave <> OLD.clave OR NEW.fijo <> OLD.fijo OR NEW.columna IS DISTINCT FROM OLD.columna THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'La clave de un campo no cambia.';
    END IF;
    IF OLD.fijo AND (NEW.tipo_dato <> OLD.tipo_dato OR NOT NEW.activo) THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('«%s» es un campo de siempre: no cambia de tipo de dato ni se desactiva.', OLD.etiqueta);
    END IF;
    IF NOT OLD.fijo AND NEW.tipo_dato <> OLD.tipo_dato THEN
      v_con_valores := EXISTS (SELECT 1 FROM public.activos a WHERE a.personalizados ? OLD.clave)
                    OR EXISTS (SELECT 1 FROM public.bajas b WHERE b.activo -> 'personalizados' ? OLD.clave);
      IF v_con_valores THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('No se puede cambiar el tipo de dato de «%s»: ya hay activos con un valor.', OLD.etiqueta);
      END IF;
    END IF;
  END IF;

  IF NEW.tipo_dato <> 'numero' THEN NEW.unidad := NULL; END IF;

  IF NEW.tipo_dato <> 'lista' THEN
    NEW.opciones := '[]'::jsonb;
  ELSE
    FOR v_o IN SELECT value FROM jsonb_array_elements(NEW.opciones) LOOP
      IF jsonb_typeof(v_o) <> 'object'
         OR coalesce(btrim(v_o ->> 'valor'), '') = '' OR coalesce(btrim(v_o ->> 'etiqueta'), '') = ''
         OR char_length(v_o ->> 'valor') > 60 OR char_length(v_o ->> 'etiqueta') > 60
         OR (v_o ? 'activo' AND jsonb_typeof(v_o -> 'activo') <> 'boolean') THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Cada opción de la lista necesita un valor y un nombre (hasta 60 caracteres).';
      END IF;
      IF (v_o ->> 'valor') = ANY (v_valores) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('La opción «%s» está repetida.', v_o ->> 'etiqueta');
      END IF;
      v_valores := v_valores || (v_o ->> 'valor');
    END LOOP;
    IF NOT EXISTS (SELECT 1 FROM jsonb_array_elements(NEW.opciones) x WHERE coalesce((x.value ->> 'activo')::boolean, true)) THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Una lista necesita al menos una opción activa.';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.tipo_dato = 'lista' AND EXISTS (
         SELECT 1 FROM jsonb_array_elements(OLD.opciones) x
          WHERE NOT ((x.value ->> 'valor') = ANY (v_valores))
            AND EXISTS (SELECT 1 FROM public.activos a WHERE a.personalizados ->> OLD.clave = x.value ->> 'valor')) THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Una opción que ya tienen activos no se quita: desactívala.';
    END IF;
  END IF;

  IF NEW.unico AND (TG_OP = 'INSERT' OR NOT OLD.unico) THEN
    IF NEW.fijo THEN
      EXECUTE format('SELECT count(*) FROM (SELECT public.f_valor_comparable(a.%1$I::text, $1) FROM public.activos a WHERE nullif(btrim(a.%1$I::text), '''') IS NOT NULL GROUP BY 1 HAVING count(*) > 1) x', NEW.columna)
        INTO v_n USING NEW.tipo_dato;
    ELSE
      SELECT count(*) INTO v_n FROM (
        SELECT public.f_valor_comparable(a.personalizados ->> NEW.clave, NEW.tipo_dato)
          FROM public.activos a
         WHERE nullif(btrim(a.personalizados ->> NEW.clave), '') IS NOT NULL
         GROUP BY 1 HAVING count(*) > 1) x;
    END IF;
    IF v_n > 0 THEN
      RAISE EXCEPTION USING ERRCODE = '23505', MESSAGE = format('No se puede marcar «%s» como único: hay %s valor%s repetido%s entre los activos.', NEW.etiqueta, v_n, CASE WHEN v_n = 1 THEN '' ELSE 'es' END, CASE WHEN v_n = 1 THEN '' ELSE 's' END);
    END IF;
  END IF;

  RETURN NEW;
END $$;

