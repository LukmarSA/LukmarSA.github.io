-- Mezcla y valida (va antes que «único»: los triggers BEFORE corren por nombre).
-- Al restaurar una baja (f_restaurar_baja) no se validan los valores: son
-- los que el activo ya tenía.
CREATE FUNCTION public.f_activos_personalizados()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  r record;
  c record;
  v_txt text;
  v_fecha date;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF jsonb_typeof(coalesce(NEW.personalizados, '{}'::jsonb)) <> 'object' THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'personalizados tiene que ser un objeto { clave: valor }.';
    END IF;
    NEW.personalizados := jsonb_strip_nulls(coalesce(OLD.personalizados, '{}'::jsonb) || coalesce(NEW.personalizados, '{}'::jsonb));
  ELSE
    NEW.personalizados := jsonb_strip_nulls(coalesce(NEW.personalizados, '{}'::jsonb));
  END IF;
  IF jsonb_typeof(NEW.personalizados) <> 'object' THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'personalizados tiene que ser un objeto { clave: valor }.';
  END IF;
  IF coalesce(current_setting('lukmar.restaurando_baja', true), '') = 'si' THEN
    RETURN NEW;
  END IF;
  FOR r IN SELECT key, value FROM jsonb_each(NEW.personalizados) LOOP
    CONTINUE WHEN TG_OP = 'UPDATE' AND (OLD.personalizados -> r.key) IS NOT DISTINCT FROM r.value;
    SELECT ca.clave, ca.etiqueta, ca.tipo_dato, ca.opciones INTO c FROM public.campos_activo ca WHERE ca.clave = r.key AND NOT ca.fijo;
    IF NOT FOUND THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('El campo «%s» no existe (o es uno de siempre, que va en su columna).', r.key);
    END IF;
    v_txt := r.value #>> '{}';
    IF c.tipo_dato = 'numero' AND jsonb_typeof(r.value) <> 'number' THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('«%s» tiene que ser un número.', c.etiqueta);
    ELSIF c.tipo_dato = 'si_no' AND jsonb_typeof(r.value) <> 'boolean' THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('«%s» tiene que ser sí o no.', c.etiqueta);
    ELSIF c.tipo_dato IN ('texto', 'texto_largo', 'fecha', 'lista') AND jsonb_typeof(r.value) <> 'string' THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('«%s» tiene que ser un texto.', c.etiqueta);
    ELSIF c.tipo_dato = 'texto' AND char_length(v_txt) > 500 THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('«%s» admite hasta 500 caracteres.', c.etiqueta);
    ELSIF c.tipo_dato = 'texto_largo' AND char_length(v_txt) > 4000 THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('«%s» admite hasta 4000 caracteres.', c.etiqueta);
    ELSIF c.tipo_dato = 'fecha' THEN
      IF v_txt !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('«%s»: la fecha no es válida.', c.etiqueta);
      END IF;
      BEGIN
        v_fecha := v_txt::date;
      EXCEPTION WHEN others THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('«%s»: la fecha no es válida.', c.etiqueta);
      END;
    ELSIF c.tipo_dato = 'lista' AND NOT EXISTS (
        SELECT 1 FROM jsonb_array_elements(c.opciones) o
         WHERE o.value ->> 'valor' = v_txt AND coalesce((o.value ->> 'activo')::boolean, true)) THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = format('«%s»: «%s» no es una de sus opciones activas.', c.etiqueta, v_txt);
    END IF;
  END LOOP;
  RETURN NEW;
END $$;

-- «Único»: el valor no se repite entre activos (solo se revisa si cambió).
-- SECURITY DEFINER: tiene que ver todos los activos, sin depender de RLS.
CREATE FUNCTION public.f_activos_campos_unicos()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  c record;
  v_nuevo text;
  v_viejo text;
  v_otro integer;
  v_prop text;
BEGIN
  FOR c IN SELECT ca.clave, ca.etiqueta, ca.tipo_dato, ca.fijo, ca.columna FROM public.campos_activo ca WHERE ca.unico ORDER BY ca.orden, ca.clave LOOP
    IF c.fijo THEN
      EXECUTE format('SELECT ($1).%1$I::text', c.columna) INTO v_nuevo USING NEW;
      IF TG_OP = 'UPDATE' THEN EXECUTE format('SELECT ($1).%1$I::text', c.columna) INTO v_viejo USING OLD; ELSE v_viejo := NULL; END IF;
    ELSE
      v_nuevo := NEW.personalizados ->> c.clave;
      v_viejo := CASE WHEN TG_OP = 'UPDATE' THEN OLD.personalizados ->> c.clave END;
    END IF;
    CONTINUE WHEN public.f_valor_comparable(v_nuevo, c.tipo_dato) IS NULL;
    CONTINUE WHEN TG_OP = 'UPDATE' AND public.f_valor_comparable(v_nuevo, c.tipo_dato) IS NOT DISTINCT FROM public.f_valor_comparable(v_viejo, c.tipo_dato);
    -- Dos altas a la vez con el mismo valor: una espera a la otra.
    PERFORM pg_advisory_xact_lock(hashtext('activos_unico:' || c.clave));
    IF c.fijo THEN
      EXECUTE format('SELECT a.id FROM public.activos a WHERE a.id <> $1 AND public.f_valor_comparable(a.%1$I::text, $2) = public.f_valor_comparable($3, $2) ORDER BY a.id LIMIT 1', c.columna)
        INTO v_otro USING NEW.id, c.tipo_dato, v_nuevo;
    ELSE
      SELECT a.id INTO v_otro FROM public.activos a
       WHERE a.id <> NEW.id AND public.f_valor_comparable(a.personalizados ->> c.clave, c.tipo_dato) = public.f_valor_comparable(v_nuevo, c.tipo_dato)
       ORDER BY a.id LIMIT 1;
    END IF;
    IF v_otro IS NOT NULL THEN
      SELECT a.propiedad INTO v_prop FROM public.activos a WHERE a.id = v_otro;
      RAISE EXCEPTION USING ERRCODE = '23505',
        MESSAGE = format('Ya hay otro activo con el mismo «%s» (%s-%s).', c.etiqueta, CASE WHEN v_prop = 'eq' THEN 'EQS' ELSE 'LKM' END, CASE WHEN length(v_otro::text) < 3 THEN lpad(v_otro::text, 3, '0') ELSE v_otro::text END);
    END IF;
  END LOOP;
  RETURN NEW;
END $$;

